// Package identity loads the sealed configuration placed into a downloaded agent package.
package identity

import (
	"bufio"
	"crypto/ed25519"
	"crypto/tls"
	"crypto/x509"
	"encoding/base64"
	"encoding/json"
	"encoding/pem"
	"errors"
	"net"
	"net/url"
	"os"
	"path/filepath"
	"strconv"
	"strings"
)

type Config struct {
	Role           string `json:"role"`
	ServerID       string `json:"serverId,omitempty"`
	ClientID       string `json:"clientId,omitempty"`
	Controller     string `json:"controller,omitempty"`
	Endpoint       string `json:"endpoint,omitempty"`
	Server         string `json:"server,omitempty"`
	PrivateKey     string `json:"privateKey,omitempty"`
	Token          string `json:"token"`
	CertificatePEM string `json:"certificatePem,omitempty"`
	CAPEM          string `json:"caPem"`
}

// ResolveConfigPath uses an explicitly supplied path when present. Downloaded
// agents otherwise load the bound JSON file beside their executable, so they
// do not depend on the shell's current working directory.
func ResolveConfigPath(requested, defaultName string) string {
	if strings.TrimSpace(requested) != "" {
		return requested
	}
	if executable, err := os.Executable(); err == nil {
		candidate := filepath.Join(filepath.Dir(executable), defaultName)
		if info, statErr := os.Stat(candidate); statErr == nil && !info.IsDir() {
			return candidate
		}
	}
	return defaultName
}

func Load(path string, role string) (Config, error) {
	contents, err := os.ReadFile(path)
	if err != nil {
		return Config{}, err
	}
	config, err := Parse(contents)
	if err != nil {
		return Config{}, err
	}
	if config.Role != role || config.Token == "" || config.CAPEM == "" {
		return Config{}, os.ErrInvalid
	}
	if role == "server" && (config.ServerID == "" || config.Endpoint == "" || config.PrivateKey == "" || config.CertificatePEM == "") {
		return Config{}, os.ErrInvalid
	}
	if role == "client" && (config.ClientID == "" || config.Server == "") {
		return Config{}, os.ErrInvalid
	}
	return config, nil
}

// Parse accepts generated JSON packages and the optional YAML-compatible form.
func Parse(contents []byte) (Config, error) {
	var config Config
	if strings.HasPrefix(strings.TrimSpace(string(contents)), "{") {
		if err := json.Unmarshal(contents, &config); err != nil {
			return Config{}, err
		}
		return config, nil
	}
	values := make(map[string]string)
	scanner := bufio.NewScanner(strings.NewReader(string(contents)))
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		key, value, found := strings.Cut(line, ":")
		if !found || strings.TrimSpace(key) == "" {
			return Config{}, errors.New("invalid config.yaml line")
		}
		key, value = strings.TrimSpace(key), strings.TrimSpace(value)
		if strings.HasPrefix(value, "\"") {
			decoded, err := strconv.Unquote(value)
			if err != nil {
				return Config{}, err
			}
			value = decoded
		}
		values[key] = value
	}
	if err := scanner.Err(); err != nil {
		return Config{}, err
	}
	config = Config{Role: values["role"], ServerID: values["serverId"], ClientID: values["clientId"], Controller: values["controller"], Endpoint: values["endpoint"], Server: values["server"], PrivateKey: values["privateKey"], Token: values["token"], CertificatePEM: values["certificatePem"], CAPEM: values["caPem"]}
	return config, nil
}

// MarshalYAML emits a deliberately small YAML subset with quoted scalars.
// Quoting keeps PEM certificates, tokens, IPv6 addresses, and URLs lossless.
func MarshalYAML(config Config) []byte {
	fields := []struct{ key, value string }{{"role", config.Role}, {"serverId", config.ServerID}, {"clientId", config.ClientID}, {"controller", config.Controller}, {"endpoint", config.Endpoint}, {"server", config.Server}, {"privateKey", config.PrivateKey}, {"token", config.Token}, {"certificatePem", config.CertificatePEM}, {"caPem", config.CAPEM}}
	var output strings.Builder
	output.WriteString("# Generated by Matrix Tunnel Proxy Controller. Keep this file private.\n")
	for _, field := range fields {
		if field.value != "" {
			output.WriteString(field.key)
			output.WriteString(": ")
			output.WriteString(strconv.Quote(field.value))
			output.WriteByte('\n')
		}
	}
	return []byte(output.String())
}

func (config Config) Certificate() (tls.Certificate, error) {
	key, err := base64.RawStdEncoding.DecodeString(config.PrivateKey)
	if err != nil || len(key) != ed25519.PrivateKeySize {
		return tls.Certificate{}, errors.New("invalid device private key")
	}
	der, err := x509.MarshalPKCS8PrivateKey(ed25519.PrivateKey(key))
	if err != nil {
		return tls.Certificate{}, err
	}
	return tls.X509KeyPair([]byte(config.CertificatePEM), pem.EncodeToMemory(&pem.Block{Type: "PRIVATE KEY", Bytes: der}))
}

func (config Config) RootPool() (*x509.CertPool, error) {
	pool, _ := x509.SystemCertPool()
	if pool == nil {
		pool = x509.NewCertPool()
	}
	if !pool.AppendCertsFromPEM([]byte(config.CAPEM)) {
		return nil, errors.New("invalid CA certificate")
	}
	return pool, nil
}

func (config Config) ServerTLSConfig() (*tls.Config, error) {
	certificate, err := config.Certificate()
	if err != nil {
		return nil, err
	}
	return &tls.Config{Certificates: []tls.Certificate{certificate}, MinVersion: tls.VersionTLS13}, nil
}

func (config Config) ClientTLSConfig() (*tls.Config, error) {
	return config.OutboundTLSConfig(config.Server)
}

func (config Config) OutboundTLSConfig(endpoint string) (*tls.Config, error) {
	pool, err := config.RootPool()
	if err != nil {
		return nil, err
	}
	if parsed, parseErr := url.Parse(endpoint); parseErr == nil && parsed.Host != "" {
		endpoint = parsed.Host
	}
	host, _, err := net.SplitHostPort(endpoint)
	if err != nil {
		host = endpoint
	}
	return &tls.Config{RootCAs: pool, ServerName: host, MinVersion: tls.VersionTLS13}, nil
}
